def greet(name):
    """แสดงข้อความทักทายตามชื่อที่ได้รับ"""
    print(f"สวัสดี, {name}!")


def is_prime(number):
    """ตรวจสอบว่าตัวเลขที่ได้รับเป็นจำนวนเฉพาะหรือไม่"""
    # ตัวเลขที่น้อยกว่า 2 ไม่ใช่จำนวนเฉพาะ
    if number < 2:
        return False

    # ตรวจสอบตัวหารตั้งแต่ 2 ถึงรากที่สองของตัวเลข
    for i in range(2, int(number ** 0.5) + 1):
        # หากหารลงตัว แสดงว่าไม่ใช่จำนวนเฉพาะ
        if number % i == 0:
            return False

    # หากไม่มีตัวหารอื่น แสดงว่าเป็นจำนวนเฉพาะ
    return True