# Lab 6.1: เครื่องคิดเลขอย่างง่ายด้วยฟังก์ชัน

def add(a, b):
    """หาผลบวกของตัวเลขสองจำนวน"""
    return a + b


def subtract(a, b):
    """หาผลลบของตัวเลขสองจำนวน"""
    return a - b


def multiply(a, b):
    """หาผลคูณของตัวเลขสองจำนวน"""
    return a * b


def divide(a, b):
    """หารตัวเลขสองจำนวน และตรวจสอบการหารด้วยศูนย์"""
    if b == 0:
        return "Error: ไม่สามารถหารด้วยศูนย์ได้"
    return a / b


def power(base, exponent=2):
    """คำนวณเลขยกกำลัง โดยกำหนดเลขชี้กำลังเริ่มต้นเป็น 2"""
    return base ** exponent


def main():
    """แสดงเมนูเครื่องคิดเลขและประมวลผลตามตัวเลือกของผู้ใช้"""
    while True:
        # แสดงเมนูการทำงานของเครื่องคิดเลข
        print("\n===== เครื่องคิดเลขอย่างง่าย =====")
        print("1. บวก (+)")
        print("2. ลบ (-)")
        print("3. คูณ (*)")
        print("4. หาร (/)")
        print("5. ยกกำลัง (**)")
        print("0. ออกจากโปรแกรม")

        # รับตัวเลือกจากผู้ใช้
        choice = input("เลือกการทำงาน (0-5): ")

        # ตรวจสอบว่าผู้ใช้ต้องการออกจากโปรแกรมหรือไม่
        if choice == "0":
            print("ขอบคุณที่ใช้เครื่องคิดเลข!")
            break

        # ตรวจสอบว่าผู้ใช้เลือกเมนูที่ถูกต้องหรือไม่
        if choice not in ["1", "2", "3", "4", "5"]:
            print("ตัวเลือกไม่ถูกต้อง กรุณาลองใหม่")
            continue

        try:
            # รับตัวเลขตัวแรกจากผู้ใช้
            num1 = float(input("ป้อนตัวเลขตัวแรก: "))

            # ตรวจสอบว่าเลือกเมนูยกกำลังหรือไม่
            if choice == "5":
                # รับเลขชี้กำลัง โดยสามารถกด Enter เพื่อใช้ค่าเริ่มต้นเป็น 2
                exponent_input = input(
                    "ป้อนเลขชี้กำลัง (กด Enter เพื่อใช้ค่าเริ่มต้น 2): "
                )

                # หากไม่ป้อนเลขชี้กำลัง ให้ใช้ค่าเริ่มต้นเป็น 2
                if exponent_input.strip() == "":
                    result = power(num1)
                else:
                    # แปลงเลขชี้กำลังให้เป็นตัวเลข
                    exponent = float(exponent_input)
                    result = power(num1, exponent)

            else:
                # รับตัวเลขตัวที่สองสำหรับการคำนวณ
                num2 = float(input("ป้อนตัวเลขตัวที่สอง: "))

                # เรียกใช้ฟังก์ชันตามเมนูที่ผู้ใช้เลือก
                if choice == "1":
                    result = add(num1, num2)
                elif choice == "2":
                    result = subtract(num1, num2)
                elif choice == "3":
                    result = multiply(num1, num2)
                elif choice == "4":
                    result = divide(num1, num2)

            # แสดงผลลัพธ์จากการคำนวณ
            print("ผลลัพธ์:", result)

        except ValueError:
            # แจ้งเตือนเมื่อผู้ใช้ป้อนข้อมูลที่ไม่ใช่ตัวเลข
            print("ข้อมูลไม่ถูกต้อง กรุณาป้อนตัวเลขเท่านั้น")


# ตรวจสอบว่าไฟล์นี้ถูกรันโดยตรงหรือไม่
if __name__ == "__main__":
    main()